import type { AdvancedVerbForm } from "@/lib/conjugate";

/**
 * 進階活用形的語意排除清單(T11.5,F7.3,寧缺勿錯):教材單字 id → 不練的形與理由。
 * 規則推導得出、但語意不成立或不自然的形,conjugate 回傳 null(活用練習不出這一題);
 * 同一個字的基本形與其他進階形照常練。依 id 而非讀音:同形異義的字語意不同
 * (出ます:出咖啡館可練命令形「出ろ」,〔零錢〕出來、發車則否)。
 *
 * 另由 conjugate.ts 依讀音處理的(不列在這裡):-aru 敬語(いらっしゃいます 等)的全部進階形、
 * 教材明說或由解說推知沒有此形的 わかります/できます/あります/見えます/聞こえます(TEXTBOOK_NO_FORM)、
 * 「〜を」前綴的可能形(L27-G02)。
 *
 * 原則:
 * - 條件形(〜ば)各動詞皆成立(あれば、わかれば),只有敬語動詞不練。
 * - 被動形:意志動詞一律練。教材以同一套變換教被動(L37-G01,含自動詞 きます → こられます)與
 *   尊敬語(L49 帰られます、来られます),自動詞的被動形(行かれる、座られる)形態上皆成立。
 * - 無意志動詞(存在、狀態、自然現象、自發變化):L33-G01「不帶意志的動詞沒有命令形」;
 *   意向(L31-G02 = 〜ましょう 的常體)、禁止(L33-G02 命令對方不要做某個動作)、可能(L27-G02 行為的
 *   能力/可能性)、被動亦不成立,只練條件形;使役只在情動・生理等自然成立者練(L48-G03 註2)。
 */
export interface FormExclusion {
  forms: readonly AdvancedVerbForm[];
  reason: string;
}

